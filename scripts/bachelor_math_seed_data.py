from __future__ import annotations

from typing import Any


def objective(prompt: str, options: dict[str, str], answer: str, analysis: str) -> dict[str, Any]:
    return {
        "prompt": prompt,
        "options": options,
        "answer": answer,
        "analysis": analysis,
    }


def subjective(prompt: str, answer: str, analysis: str) -> dict[str, str]:
    return {"prompt": prompt, "answer": answer, "analysis": analysis}


def topic(
    stage: str,
    course: str,
    knowledge_tag: str,
    fine_tag: str,
    difficulty: int,
    choice: dict[str, Any],
    blank: dict[str, str],
    calculation: dict[str, str],
    proof: dict[str, str],
    comprehensive: dict[str, str],
) -> dict[str, Any]:
    return {
        "stage": stage,
        "course": course,
        "knowledge_tag": knowledge_tag,
        "fine_tag": fine_tag,
        "difficulty": difficulty,
        "choice": choice,
        "blank": blank,
        "calculation": calculation,
        "proof": proof,
        "comprehensive": comprehensive,
    }


